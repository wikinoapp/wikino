// genoperationsは、OpenAPI記述の各operationの分類 (x-wikino-operation) から、
// apigenパッケージのoperationの表 (operations.gen.go) を生成する。
//
// 確認プロトコルの対象と `--dry-run` で送らない要求を、CLIのコードに一覧を持たずに
// この表から決めるために使う。oapi-codegenは拡張項目を生成物に含めないため、別に生成する。
//
// 使い方: go run ./internal/apigen/genoperations -spec ../go/api/openapi.yaml -o internal/apigen/operations.gen.go
package main

import (
	"bytes"
	"errors"
	"flag"
	"fmt"
	"go/format"
	"os"
	"sort"
	"strings"

	"go.yaml.in/yaml/v3"
)

// httpMethodsは、OpenAPIのPath Itemでoperationを持つキーを、表に並べる順にしたもの。
var httpMethods = []string{"get", "put", "post", "delete", "options", "head", "patch", "trace"}

type document struct {
	Paths map[string]map[string]yaml.Node `yaml:"paths"`
}

type operationObject struct {
	OperationID string               `yaml:"operationId"`
	Class       *operationExtensions `yaml:"x-wikino-operation"`
}

// operationExtensionsは、x-wikino-operationの形。
// 書き忘れを既定値で黙って補わないよう、ポインタで受けて欠けた項目を検出する。
type operationExtensions struct {
	ReadOnly             *bool `yaml:"read_only"`
	Irreversible         *bool `yaml:"irreversible"`
	Idempotent           *bool `yaml:"idempotent"`
	ConfirmationRequired *bool `yaml:"confirmation_required"`
}

type operation struct {
	id                   string
	method               string
	path                 string
	readOnly             bool
	irreversible         bool
	idempotent           bool
	confirmationRequired bool
}

func main() {
	specPath := flag.String("spec", "", "OpenAPI記述のパス")
	outPath := flag.String("o", "", "出力するGoのファイルのパス")
	flag.Parse()

	if err := run(*specPath, *outPath); err != nil {
		fmt.Fprintln(os.Stderr, "genoperations:", err)
		os.Exit(1)
	}
}

func run(specPath, outPath string) error {
	if specPath == "" || outPath == "" {
		return errors.New("-specと-oを指定してください")
	}

	data, err := os.ReadFile(specPath) // #nosec G304 -- 開発者が渡すOpenAPI記述のパスを読む
	if err != nil {
		return err
	}

	ops, err := parse(data)
	if err != nil {
		return err
	}

	src, err := render(ops)
	if err != nil {
		return err
	}

	return os.WriteFile(outPath, src, 0o600)
}

func parse(data []byte) ([]operation, error) {
	var doc document
	if err := yaml.Unmarshal(data, &doc); err != nil {
		return nil, err
	}

	paths := make([]string, 0, len(doc.Paths))
	for path := range doc.Paths {
		paths = append(paths, path)
	}
	sort.Strings(paths)

	var ops []operation
	for _, path := range paths {
		item := doc.Paths[path]
		for _, method := range httpMethods {
			node, ok := item[method]
			if !ok {
				continue
			}

			var obj operationObject
			if err := node.Decode(&obj); err != nil {
				return nil, fmt.Errorf("%s %s: %w", strings.ToUpper(method), path, err)
			}

			op, err := toOperation(strings.ToUpper(method), path, obj)
			if err != nil {
				return nil, err
			}
			ops = append(ops, op)
		}
	}

	if len(ops) == 0 {
		return nil, errors.New("operationが1つもありません")
	}

	return ops, nil
}

func toOperation(method, path string, obj operationObject) (operation, error) {
	where := fmt.Sprintf("%s %s", method, path)
	if obj.OperationID == "" {
		return operation{}, fmt.Errorf("%s: operationIdがありません", where)
	}
	where = fmt.Sprintf("%s (%s)", where, obj.OperationID)

	c := obj.Class
	if c == nil {
		return operation{}, fmt.Errorf("%s: x-wikino-operationがありません", where)
	}
	if c.ReadOnly == nil || c.Irreversible == nil || c.Idempotent == nil || c.ConfirmationRequired == nil {
		return operation{}, fmt.Errorf("%s: x-wikino-operationにはread_only・irreversible・idempotent・confirmation_requiredをすべて書いてください", where)
	}

	return operation{
		id:                   obj.OperationID,
		method:               method,
		path:                 path,
		readOnly:             *c.ReadOnly,
		irreversible:         *c.Irreversible,
		idempotent:           *c.Idempotent,
		confirmationRequired: *c.ConfirmationRequired,
	}, nil
}

func render(ops []operation) ([]byte, error) {
	var b bytes.Buffer
	b.WriteString(`// Code generated by genoperations from go/api/openapi.yaml. DO NOT EDIT.

package apigen

// Operationは、OpenAPI記述の1つのoperationと、その分類 (x-wikino-operation)。
type Operation struct {
	// IDはoperationId。
	ID string
	// MethodはHTTPメソッド (大文字)。
	Method string
	// Pathはサーバーの基底のURL (/api/v1) からのパスのテンプレート。
	Path string
	// ReadOnlyは、状態を変えない操作か。
	ReadOnly bool
	// Irreversibleは、取り消せない変更か。
	Irreversible bool
	// Idempotentは、同じ要求を繰り返しても結果が変わらないか。
	Idempotent bool
	// ConfirmationRequiredは、実行の前に利用者の確認を求めるべきか。
	ConfirmationRequired bool
}

// Operationsは、OpenAPI記述のすべてのoperation。パスとメソッドの順に並ぶ。
var Operations = []Operation{
`)
	for _, op := range ops {
		fmt.Fprintf(&b, "\t{ID: %q, Method: %q, Path: %q, ReadOnly: %t, Irreversible: %t, Idempotent: %t, ConfirmationRequired: %t},\n",
			op.id, op.method, op.path, op.readOnly, op.irreversible, op.idempotent, op.confirmationRequired)
	}
	b.WriteString("}\n")

	return format.Source(b.Bytes())
}
